/**
 * Visual styling of TodoPaper documents: line classes for projects, tasks,
 * notes and done items, plus marks for tags, links, bold text and
 * user-defined custom styles. Only lines in the viewport are decorated.
 */

import { Facet, Range } from "@codemirror/state";
import { Decoration, DecorationSet, EditorView, ViewPlugin, ViewUpdate } from "@codemirror/view";
import { findBold, findLinks } from "../core/parser";
import { outlineField } from "./model";

/** A user-defined style applied to lines containing `match`. */
export interface CustomStyleRule {
  /** CSS class to apply (styles are generated by the UI layer). */
  className: string;
  /** Case-insensitive text a line must contain. */
  match: string;
  /** Style the entire line instead of just the matched text. */
  wholeLine: boolean;
}

export const customStyleRules = Facet.define<CustomStyleRule[], CustomStyleRule[]>({
  combine: (values) => values.flat(),
});

const lineDeco = {
  project0: Decoration.line({ class: "cm-tp-project cm-tp-project-top" }),
  projectSub: Decoration.line({ class: "cm-tp-project cm-tp-project-sub" }),
  task: Decoration.line({ class: "cm-tp-task" }),
  note: Decoration.line({ class: "cm-tp-note" }),
  taskDone: Decoration.line({ class: "cm-tp-task cm-tp-done" }),
  noteDone: Decoration.line({ class: "cm-tp-note cm-tp-done" }),
  projectDone0: Decoration.line({ class: "cm-tp-project cm-tp-project-top cm-tp-done" }),
  projectDoneSub: Decoration.line({ class: "cm-tp-project cm-tp-project-sub cm-tp-done" }),
};
const dashMark = Decoration.mark({ class: "cm-tp-dash" });
const linkMark = Decoration.mark({ class: "cm-tp-link" });
const boldMark = Decoration.mark({ class: "cm-tp-bold" });
const contentMark = Decoration.mark({ class: "cm-tp-content" });
const tagMarks = new Map<string, Decoration>();

/** Mark decoration for a tag, carrying its name for CSS hooks and clicks. */
function tagMark(name: string): Decoration {
  const key = name.toLowerCase();
  let deco = tagMarks.get(key);
  if (!deco) {
    deco = Decoration.mark({ class: "cm-tp-tag", attributes: { "data-tag": key } });
    tagMarks.set(key, deco);
  }
  return deco;
}

/** Pick the line decoration for a parsed line. */
function lineDecoFor(type: string, level: number, done: boolean): Decoration | null {
  if (type === "project") {
    if (done) return level === 0 ? lineDeco.projectDone0 : lineDeco.projectDoneSub;
    return level === 0 ? lineDeco.project0 : lineDeco.projectSub;
  }
  if (type === "task") return done ? lineDeco.taskDone : lineDeco.task;
  if (type === "note") return done ? lineDeco.noteDone : lineDeco.note;
  return null;
}

/** Add custom style decorations for one line. */
function addCustomStyles(rules: CustomStyleRule[], text: string, from: number, out: Range<Decoration>[]) {
  const lower = text.toLowerCase();
  for (const rule of rules) {
    const needle = rule.match.toLowerCase();
    if (!needle || !lower.includes(needle)) continue;
    if (rule.wholeLine) {
      out.push(Decoration.line({ class: rule.className }).range(from));
      continue;
    }
    for (let i = lower.indexOf(needle); i >= 0; i = lower.indexOf(needle, i + needle.length)) {
      out.push(Decoration.mark({ class: rule.className }).range(from + i, from + i + needle.length));
    }
  }
}

/** Build decorations for the visible part of the document. */
function buildDecorations(view: EditorView): DecorationSet {
  const { state } = view;
  const outline = state.field(outlineField);
  const rules = state.facet(customStyleRules);
  const out: Range<Decoration>[] = [];
  for (const { from, to } of view.visibleRanges) {
    let pos = from;
    while (pos <= to) {
      const line = state.doc.lineAt(pos);
      const info = outline.infos[line.number - 1];
      const deco = info && lineDecoFor(info.type, info.level, info.done);
      if (info && deco) {
        out.push(deco.range(line.from));
        const text = line.text;
        if (info.type === "task") out.push(dashMark.range(line.from + info.indentEnd, line.from + info.indentEnd + 1));
        const contentStart = line.from + info.indentEnd + (info.type === "task" ? 2 : 0);
        if (line.to > contentStart) out.push(contentMark.range(contentStart, line.to));
        for (const tag of info.tags) out.push(tagMark(tag.name).range(line.from + tag.from, line.from + tag.to));
        for (const s of findLinks(text)) out.push(linkMark.range(line.from + s.from, line.from + s.to));
        for (const s of findBold(text)) out.push(boldMark.range(line.from + s.from, line.from + s.to));
        if (rules.length) addCustomStyles(rules, text, line.from, out);
      }
      pos = line.to + 1;
    }
  }
  return Decoration.set(out, true);
}

export const highlightPlugin = ViewPlugin.fromClass(
  class {
    decorations: DecorationSet;
    constructor(view: EditorView) {
      this.decorations = buildDecorations(view);
    }
    update(update: ViewUpdate) {
      const rulesChanged = update.startState.facet(customStyleRules) !== update.state.facet(customStyleRules);
      if (update.docChanged || update.viewportChanged || rulesChanged) this.decorations = buildDecorations(update.view);
    }
  },
  { decorations: (v) => v.decorations },
);
